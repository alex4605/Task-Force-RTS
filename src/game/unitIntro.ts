/** The model as a flight name shows it: the intro name without a trailing role word ("Il-10 強擊機" → "Il-10"). */
export function modelLabel(model: AircraftModel): string {
  const name = AIR_INTRO[model]?.[0];
  if (!name) return model.toUpperCase();
  return name.replace(/\s\S*(戰鬥機|轟炸機|強擊機|攻擊機|雙翼機|直升機)$/, '');
}

/** An enemy flight: aircraft, task and number in the flight, e.g. "Su-27 側衛 攔截 #2". */
export function flightName(model: AircraftModel, task: string, n: number): string {
  return `${modelLabel(model)} ${task} #${n}`;
}
